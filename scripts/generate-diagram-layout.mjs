import fs from "node:fs";
import path from "node:path";
import ELK from "elkjs/lib/elk.bundled.js";

const repo = process.cwd();
const specPath = path.join(repo, "diagram-specs", "rag.json");
const outPath = path.join(repo, "src", "diagram", "generated", "ragLayout.ts");
const spec = JSON.parse(fs.readFileSync(specPath, "utf8"));

const sizeFor = (type) => {
  if (type === "database" || type === "model") return {width: 250, height: 126};
  if (type === "actor") return {width: 210, height: 108};
  return {width: 240, height: 116};
};

const elk = new ELK();
const graph = {
  id: "root",
  layoutOptions: {
    "elk.algorithm": "layered",
    "elk.direction": spec.direction ?? "RIGHT",
    "elk.edgeRouting": "ORTHOGONAL",
    "elk.spacing.nodeNode": "64",
    "elk.layered.spacing.nodeNodeBetweenLayers": "110",
    "elk.layered.nodePlacement.strategy": "NETWORK_SIMPLEX",
    "elk.layered.crossingMinimization.strategy": "LAYER_SWEEP",
    "elk.padding": "[top=40,left=40,bottom=40,right=40]"
  },
  children: spec.nodes.map((node) => ({id: node.id, ...sizeFor(node.type)})),
  edges: spec.edges.map((edge) => ({id: edge.id, sources: [edge.source], targets: [edge.target]}))
};

const result = await elk.layout(graph);
const nodeById = new Map(spec.nodes.map((n) => [n.id, n]));
const edgeById = new Map(spec.edges.map((e) => [e.id, e]));

const layout = {
  width: result.width ?? 1,
  height: result.height ?? 1,
  nodes: (result.children ?? []).map((node) => ({
    ...nodeById.get(node.id),
    x: node.x ?? 0,
    y: node.y ?? 0,
    width: node.width ?? 240,
    height: node.height ?? 116
  })),
  edges: (result.edges ?? []).map((edge) => {
    const section = edge.sections?.[0];
    const points = section
      ? [section.startPoint, ...(section.bendPoints ?? []), section.endPoint].map((p) => ({x: p.x, y: p.y}))
      : [];
    return {...edgeById.get(edge.id), points};
  })
};

fs.mkdirSync(path.dirname(outPath), {recursive: true});
fs.writeFileSync(outPath, `// Generated by scripts/generate-diagram-layout.mjs\nexport const ragLayout = ${JSON.stringify(layout, null, 2)};\n`);
console.log(`Generated ${outPath}`);
