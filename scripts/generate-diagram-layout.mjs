import fs from "node:fs";
import path from "node:path";
import ELK from "elkjs/lib/elk.bundled.js";

const repo = process.cwd();
const specDir = path.join(repo, "diagram-specs");
const outDir = path.join(repo, "src", "diagram", "generated");
const elk = new ELK();

const sizeFor = (type) => {
  if (type === "database" || type === "model") return {width: 250, height: 126};
  if (type === "actor") return {width: 210, height: 108};
  if (type === "document") return {width: 240, height: 112};
  if (type === "gateway" || type === "compute") return {width: 248, height: 118};
  return {width: 240, height: 116};
};

const toCamel = (value) => value
  .replace(/\.(json|jsonl)$/i, "")
  .replace(/[-_]+(.)?/g, (_, c) => c ? c.toUpperCase() : "")
  .replace(/^(.)/, (m) => m.toLowerCase());

const readSpecs = (filePath) => {
  const raw = fs.readFileSync(filePath, "utf8").trim();
  if (filePath.endsWith(".jsonl")) {
    return raw.split(/\r?\n/).filter(Boolean).map((line) => JSON.parse(line));
  }
  return [JSON.parse(raw)];
};

const buildLayout = async (spec) => {
  const graph = {
    id: "root",
    layoutOptions: {
      "elk.algorithm": "layered",
      "elk.direction": spec.direction ?? "RIGHT",
      "elk.edgeRouting": "ORTHOGONAL",
      "elk.spacing.nodeNode": "68",
      "elk.layered.spacing.nodeNodeBetweenLayers": "116",
      "elk.layered.nodePlacement.strategy": "NETWORK_SIMPLEX",
      "elk.layered.crossingMinimization.strategy": "LAYER_SWEEP",
      "elk.padding": "[top=44,left=44,bottom=44,right=44]"
    },
    children: spec.nodes.map((node) => ({id: node.id, ...sizeFor(node.type)})),
    edges: spec.edges.map((edge) => ({id: edge.id, sources: [edge.source], targets: [edge.target]}))
  };

  const result = await elk.layout(graph);
  const nodeById = new Map(spec.nodes.map((n) => [n.id, n]));
  const edgeById = new Map(spec.edges.map((e) => [e.id, e]));

  return {
    width: result.width ?? 1,
    height: result.height ?? 1,
    nodes: (result.children ?? []).map((node) => ({
      ...nodeById.get(node.id),
      x: node.x ?? 0,
      y: node.y ?? 0,
      width: node.width ?? 240,
      height: node.height ?? 116
    })),
    edges: (result.edges ?? []).map((edge) => {
      const section = edge.sections?.[0];
      const points = section
        ? [section.startPoint, ...(section.bendPoints ?? []), section.endPoint].map((p) => ({x: p.x, y: p.y}))
        : [];
      return {...edgeById.get(edge.id), points};
    })
  };
};

fs.mkdirSync(outDir, {recursive: true});
const files = fs.readdirSync(specDir).filter((name) => /\.(json|jsonl)$/i.test(name));

for (const file of files) {
  const specs = readSpecs(path.join(specDir, file));
  for (let i = 0; i < specs.length; i += 1) {
    const spec = specs[i];
    const base = spec.id ? toCamel(spec.id) : `${toCamel(file)}${i || ""}`;
    const exportName = `${base}Layout`;
    const outPath = path.join(outDir, `${exportName}.ts`);
    const layout = await buildLayout(spec);
    fs.writeFileSync(outPath, `// Generated by scripts/generate-diagram-layout.mjs\nexport const ${exportName} = ${JSON.stringify(layout, null, 2)};\n`);
    console.log(`Generated ${outPath}`);
  }
}
